-- Bharat Health Grid
-- MySQL 8+ / MariaDB 10.2+ schema and sample data for India's PHC network.
-- Reference date for stock, bed, and attendance snapshots: 2026-09-26.
-- Re-running this script drops and recreates the database bharat_health_grid.
--
-- Demo situations encoded in the seed:
-- A  TN-CBE-SUL  Paracetamol batch PARA-TN-CBE-SUL-2606 is nearly exhausted and heavily used.
-- B  TN-TNJ-PTK  Paracetamol batch PARA-TN-TNJ-PTK-2603 is far above local consumption.
-- C  KL-KKD-BAL  Insulin batch INS-KL-KKD-BAL-2604 expires on 2026-10-25.
-- D  Pune district (Mulshi, Baramati, Junnar) patient footfall rises across 30 days.
--    Baramati also spikes on 2026-09-16.
-- E  OD-GNJ-DIG  5 of 6 beds occupied on 2026-09-26.
-- F  RJ-JAI-BAS  the medical officer is on leave and other staff are repeatedly absent.

DROP DATABASE IF EXISTS bharat_health_grid;
CREATE DATABASE bharat_health_grid
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;
USE bharat_health_grid;

SET NAMES utf8mb4;

CREATE TABLE states (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(100) NOT NULL,
  code CHAR(2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_states_name (name),
  UNIQUE KEY uq_states_code (code)
) ENGINE=InnoDB;

CREATE TABLE districts (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  state_id INT UNSIGNED NOT NULL,
  name VARCHAR(100) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_districts_state_name (state_id, name),
  CONSTRAINT fk_districts_state FOREIGN KEY (state_id) REFERENCES states (id)
) ENGINE=InnoDB;

CREATE TABLE phcs (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  district_id INT UNSIGNED NOT NULL,
  name VARCHAR(150) NOT NULL,
  phc_code VARCHAR(20) NOT NULL,
  latitude DECIMAL(9, 6) NOT NULL,
  longitude DECIMAL(9, 6) NOT NULL,
  population_covered INT UNSIGNED NOT NULL,
  status ENUM('active', 'inactive') NOT NULL DEFAULT 'active',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_phcs_code (phc_code),
  KEY idx_phcs_district_id (district_id),
  CONSTRAINT fk_phcs_district FOREIGN KEY (district_id) REFERENCES districts (id)
) ENGINE=InnoDB;

CREATE TABLE medicines (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(100) NOT NULL,
  generic_name VARCHAR(150) NOT NULL,
  category VARCHAR(50) NOT NULL,
  unit VARCHAR(20) NOT NULL,
  reorder_level INT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_medicines_name (name)
) ENGINE=InnoDB;

CREATE TABLE medicine_stock (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  phc_id INT UNSIGNED NOT NULL,
  medicine_id INT UNSIGNED NOT NULL,
  batch_number VARCHAR(40) NOT NULL,
  quantity_received INT UNSIGNED NOT NULL,
  current_quantity INT UNSIGNED NOT NULL,
  daily_average_usage DECIMAL(8, 2) NOT NULL,
  received_date DATE NOT NULL,
  expiry_date DATE NOT NULL,
  supplier_name VARCHAR(150) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_medicine_stock_batch (phc_id, medicine_id, batch_number),
  KEY idx_medicine_stock_expiry (expiry_date),
  CONSTRAINT fk_medicine_stock_phc FOREIGN KEY (phc_id) REFERENCES phcs (id),
  CONSTRAINT fk_medicine_stock_medicine FOREIGN KEY (medicine_id) REFERENCES medicines (id),
  CONSTRAINT chk_medicine_stock_quantity CHECK (current_quantity <= quantity_received),
  CONSTRAINT chk_medicine_stock_dates CHECK (expiry_date > received_date)
) ENGINE=InnoDB;

CREATE TABLE beds (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  phc_id INT UNSIGNED NOT NULL,
  total_beds INT UNSIGNED NOT NULL,
  occupied_beds INT UNSIGNED NOT NULL,
  available_beds INT UNSIGNED NOT NULL,
  last_updated DATETIME NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_beds_phc (phc_id),
  CONSTRAINT fk_beds_phc FOREIGN KEY (phc_id) REFERENCES phcs (id),
  CONSTRAINT chk_beds_balance CHECK (occupied_beds + available_beds = total_beds)
) ENGINE=InnoDB;

CREATE TABLE personnel (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  phc_id INT UNSIGNED NOT NULL,
  name VARCHAR(120) NOT NULL,
  role ENUM('Doctor', 'Nurse', 'Pharmacist', 'Lab Technician', 'Health Worker') NOT NULL,
  specialization VARCHAR(100) NOT NULL,
  employment_status ENUM('active', 'on_leave', 'inactive') NOT NULL DEFAULT 'active',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_personnel_id_phc (id, phc_id),
  KEY idx_personnel_phc_id (phc_id),
  CONSTRAINT fk_personnel_phc FOREIGN KEY (phc_id) REFERENCES phcs (id)
) ENGINE=InnoDB;

CREATE TABLE personnel_attendance (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  personnel_id INT UNSIGNED NOT NULL,
  phc_id INT UNSIGNED NOT NULL,
  attendance_date DATE NOT NULL,
  status ENUM('Present', 'Absent', 'Leave') NOT NULL,
  check_in TIME NULL,
  check_out TIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_attendance_person_date (personnel_id, attendance_date),
  KEY idx_attendance_phc_date (phc_id, attendance_date),
  CONSTRAINT fk_attendance_personnel_phc FOREIGN KEY (personnel_id, phc_id) REFERENCES personnel (id, phc_id),
  CONSTRAINT chk_attendance_times CHECK (
    (status = 'Present' AND check_in IS NOT NULL AND check_out IS NOT NULL AND check_out > check_in)
    OR (status <> 'Present' AND check_in IS NULL AND check_out IS NULL)
  )
) ENGINE=InnoDB;

CREATE TABLE patient_footfall (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  phc_id INT UNSIGNED NOT NULL,
  record_date DATE NOT NULL,
  total_patients INT UNSIGNED NOT NULL,
  emergency_patients INT UNSIGNED NOT NULL,
  outpatient_patients INT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_footfall_phc_date (phc_id, record_date),
  KEY idx_footfall_record_date (record_date),
  CONSTRAINT fk_footfall_phc FOREIGN KEY (phc_id) REFERENCES phcs (id),
  CONSTRAINT chk_footfall_parts CHECK (emergency_patients + outpatient_patients = total_patients)
) ENGINE=InnoDB;

